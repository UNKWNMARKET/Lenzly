// Deduplicated and sorted
const seen = new Set<string>()
export const HASHTAGS = TOP_HASHTAGS.filter(h => {
  const clean = h.toLowerCase()
  if (seen.has(clean)) return false
  seen.add(clean)
  return true
})

export function suggestHashtags(query: string, limit = 8): string[] {
  const q = query.toLowerCase().replace(/^#/, '')
  if (!q) return HASHTAGS.slice(0, limit)
  return HASHTAGS.filter(h => h.slice(1).includes(q)).slice(0, limit)
}

export function extractHashtags(text: string): string[] {
  const matches = text.match(/#[a-zA-Z][a-zA-Z0-9_]*/g) ?? []
  return [...new Set(matches.map(t => t.toLowerCase()))]
}
